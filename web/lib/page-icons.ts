export const PAGE_ICONS = Object.keys(PAGE_ICON_MAP);

const ICON_VALUE = /^icon:([a-z0-9-]+):(#[0-9a-fA-F]{6})$/;

export function pageIconValue(name: string, color: string) {
  return `icon:${name}:${color}`;
}

export function parsePageIcon(value: string | null | undefined) {
  if (!value) return null;
  const match = value.match(ICON_VALUE);
  if (match?.[1] && match[2] && PAGE_ICON_MAP[match[1]]) {
    return { kind: "icon" as const, name: match[1], color: match[2] };
  }
  return { kind: "emoji" as const, emoji: value };
}

export function emojiWithTone(item: EmojiItem, tone: string) {
  if (!item.tone || !tone) return item.emoji;
  return `${item.emoji}${tone}`;
}
